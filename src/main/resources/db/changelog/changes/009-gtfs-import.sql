--comment: History of the GTFS imports: the dataset version imported (its Opendatasoft processing date) and how it went
CREATE TABLE public.gtfs_import (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source        varchar(16)  NOT NULL CHECK (source IN ('WATCH', 'MANUAL')),
    feed_date     timestamptz,
    started_at    timestamptz  NOT NULL DEFAULT now(),
    finished_at   timestamptz,
    status        varchar(16)  NOT NULL CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED')),
    row_counts    text,
    error         text
);
CREATE INDEX gtfs_import_started_at_idx ON public.gtfs_import (started_at DESC);

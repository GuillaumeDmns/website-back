--comment: User favorites, synced between devices: home / work (one each), saved places, stop areas and lines
CREATE TABLE public.favorite (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       integer      NOT NULL REFERENCES public."user" (id) ON DELETE CASCADE,
    kind          varchar(16)  NOT NULL CHECK (kind IN ('HOME', 'WORK', 'PLACE', 'STOP', 'LINE')),
    label         varchar(200),
    stop_area_id  varchar(64),
    line_id       varchar(32),
    lat           double precision,
    lon           double precision,
    created_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX favorite_user_id_idx ON public.favorite (user_id);
-- One home and one work per user, a stop area or a line saved once
CREATE UNIQUE INDEX favorite_home_work_key ON public.favorite (user_id, kind) WHERE kind IN ('HOME', 'WORK');
CREATE UNIQUE INDEX favorite_stop_key ON public.favorite (user_id, stop_area_id) WHERE kind = 'STOP';
CREATE UNIQUE INDEX favorite_line_key ON public.favorite (user_id, line_id) WHERE kind = 'LINE';

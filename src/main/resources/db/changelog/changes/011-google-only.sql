--changeset gdamiens:api-token
--comment: Personal API tokens of the admins (Bruno, scripts): only their SHA-256 hash is stored, exchanged for an access JWT
CREATE TABLE public.api_token (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       integer      NOT NULL REFERENCES public."user" (id) ON DELETE CASCADE,
    name          varchar(100) NOT NULL,
    token_hash    varchar(64)  NOT NULL UNIQUE,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    expires_at    timestamptz  NOT NULL,
    last_used_at  timestamptz
);
CREATE INDEX api_token_user_id_idx ON public.api_token (user_id);
